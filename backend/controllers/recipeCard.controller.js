// @desc    Generate an AI image for a recipe
// @route   POST /api/recipes/:id/generate-image
// @access  Private
export const generateRecipeImageController = async (req, res) => {
  try {
    const { id: recipeId } = req.params;
    const user = await User.findOne({ firebaseUID: req.user.uid });

    if (!user) {
      return res.status(404).json({ success: false, message: "User not found." });
    }

    const recipe = await Recipe.findById(recipeId);
    if (!recipe) {
      return res.status(404).json({ success: false, message: "Recipe not found." });
    }

    // Authorization check
    if (!recipe.generatedBy || !recipe.generatedBy.equals(user._id)) {
      return res.status(403).json({ success: false, message: "User not authorized to generate image for this recipe." });
    }

    // Check for existing image for editing
    let existingImageBuffer = null;
    if (recipe.recipeImage && recipe.recipeImage.original) {
      try {
        // Parse GCS path from public URL
        // Example: https://storage.googleapis.com/bucket-name/image-prefix/users/userId/recipes/recipeId/filename.webp
        const url = new URL(recipe.recipeImage.original);
        const pathSegments = url.pathname.split('/').filter(Boolean);
        // pathSegments[0] is bucket name, others are the file path
        const gcsFilePath = pathSegments.slice(1).join('/');
        
        console.log(`[generateRecipeImageController] Downloading existing image for editing: ${gcsFilePath}`);
        existingImageBuffer = await downloadFileAsBuffer(gcsFilePath);
      } catch (err) {
        console.error("[generateRecipeImageController] Failed to download existing image, proceeding with new generation:", err);
      }
    }

    // Generate/Edit the image
    let imageBuffer = await generateRecipeImage(recipe, existingImageBuffer);

    if (ENABLE_RECIPE_IMAGE_CROP_4_3) {
      console.log('[generateRecipeImageController] Cropping image to 4:3 (env enabled).');
      imageBuffer = await cropImageBufferToFourThree(imageBuffer);
    }

    // Increment image version
    recipe.imageVersion = (recipe.imageVersion || 0) + 1;
    const newVersion = recipe.imageVersion;

    // Determine filename base
    let filenameSlug = 'recipe';
    
    if (recipe.slug) {
      filenameSlug = recipe.slug;
    } else if (recipe.seoSlugCandidate) {
      // Simple slugify for candidate
      filenameSlug = recipe.seoSlugCandidate
        .toLowerCase()
        .replace(/[^a-z0-9]+/g, '-')
        .replace(/^-+|-+$/g, '');
    } else if (recipe.recipeTitle) {
      // Fallback to title
      filenameSlug = recipe.recipeTitle
        .toLowerCase()
        .replace(/[^a-z0-9]+/g, '-')
        .replace(/^-+|-+$/g, '');
    }

    const filenameBase = `${filenameSlug}-v${newVersion}`;

    // Process and upload images (same logic as uploadRecipeImage)
    const sizes = {
      thumbnail: { width: 480, fit: 'cover', quality: 80 },
      display: { width: 800, fit: 'inside', quality: 85 },
      original: { quality: 90 },
    };

    const imageUrls = {};
    const imageProcessor = sharp(imageBuffer);

    for (const [key, settings] of Object.entries(sizes)) {
      let processor = imageProcessor.clone();
      if (settings.width) {
        processor = processor.resize({ width: settings.width, height: settings.height, fit: settings.fit });
      }
      const buffer = await processor.webp({ quality: settings.quality }).toBuffer();
      const destination = `users/${user._id}/recipes/${recipeId}/${filenameBase}-${key}.webp`;
      imageUrls[key] = await uploadBufferToGCS(buffer, destination);
    }

    // Update recipe
    recipe.recipeImage = imageUrls;
    await recipe.save();

    res.status(200).json({
      success: true,
      message: 'Image generated successfully.',
      data: imageUrls // Return the new image object
    });

  } catch (error) {
    console.error('Error generating recipe image:', error);
    res.status(500).json({
      success: false,
      message: "Error generating image.",
      error: error.message
    });
  }
};


// @desc    Update recipe metadata (title, description, times, diet, meal type, yield)
// @route   PATCH /api/recipes/:id/metadata
// @access  Private
export const updateRecipeMetadata = async (req, res) => {
  try {
    console.log('[updateRecipeMetadata] Request received for recipe ID:', req.params.id);
    const { recipeTitle, recipeDescription, prepTime, cookTime, totalTime, recipeDiet, mealType, recipeYield } = req.body;

    const recipe = await Recipe.findById(req.params.id);
    if (!recipe) {
      return res.status(404).json({ success: false, message: "Recipe not found." });
    }

    // Verify user owns the recipe
    const user = await User.findOne({ firebaseUID: req.user.uid });
    if (!user) {
      return res.status(404).json({ success: false, message: "User not found." });
    }

    if (!recipe.generatedBy.equals(user._id)) {
      return res.status(403).json({ 
        success: false, 
        message: "You can only edit recipes you created." 
      });
    }

    // Update the metadata fields
    if (recipeTitle !== undefined) recipe.recipeTitle = recipeTitle;
    if (recipeDescription !== undefined) recipe.recipeDescription = recipeDescription;
    if (prepTime !== undefined) recipe.prepTime = prepTime;
    if (cookTime !== undefined) recipe.cookTime = cookTime;
    if (totalTime !== undefined) recipe.totalTime = totalTime;
    if (recipeDiet !== undefined) recipe.recipeDiet = recipeDiet;
    if (mealType !== undefined) recipe.mealType = mealType;
    if (recipeYield !== undefined) recipe.recipeYield = recipeYield;

    const updatedRecipe = await recipe.save();
    console.log('[updateRecipeMetadata] Recipe metadata updated successfully');

    res.status(200).json({
      success: true,
      message: "Recipe metadata updated successfully.",
      data: updatedRecipe,
    });
  } catch (error) {
    console.error('[updateRecipeMetadata] Error updating recipe metadata:', error);
    res.status(500).json({ 
      success: false, 
      message: "Error updating recipe metadata.", 
      error: error.message,
      stack: process.env.NODE_ENV === 'development' ? error.stack : undefined
    });
  }
};

// @desc    Duplicate a recipe with a new title
// @route   POST /api/recipes/:id/duplicate
// @access  Private
export const duplicateRecipe = async (req, res) => {
  try {
    console.log('[duplicateRecipe] Request received for recipe ID:', req.params.id);
    const { newTitle } = req.body;

    if (!newTitle || typeof newTitle !== 'string' || newTitle.trim().length === 0) {
      return res.status(400).json({ 
        success: false, 
        message: "New title is required and must be a non-empty string." 
      });
    }

    // Find the original recipe
    const originalRecipe = await Recipe.findById(req.params.id);
    if (!originalRecipe) {
      return res.status(404).json({ success: false, message: "Recipe not found." });
    }

    // Allow duplication if:
    // 1. User owns the recipe, OR
    // 2. Recipe is publicly visible (public or unlisted)
    const user = await User.findOne({ firebaseUID: req.user.uid });
    if (!user) {
      return res.status(404).json({ success: false, message: "User not found." });
    }
    
    const isOwner = originalRecipe.generatedBy.equals(user._id);
    const isExternallyVisible = originalRecipe.visibility && originalRecipe.visibility !== 'private';
    
    if (!isOwner && !isExternallyVisible) {
      return res.status(403).json({ 
        success: false, 
        message: "You can only duplicate your own recipes or publicly visible recipes." 
      });
    }

    // Create a duplicate with the new title
    const duplicateData = originalRecipe.toObject();
    delete duplicateData._id;
    delete duplicateData.slug;
    delete duplicateData.createdAt;
    delete duplicateData.updatedAt;
    delete duplicateData.__v;
    
    // Set the new owner to the current user (important for copied public recipes)
    duplicateData.generatedBy = user._id;
    duplicateData.recipeTitle = newTitle.trim();
    duplicateData.visibility = 'private';
    duplicateData.isPublic = false; // New copy should be private by default
    duplicateData.ratings = []; // Reset ratings for the new copy
    duplicateData.savedBy = [user._id]; // Initialize savedBy with the new owner

    const duplicatedRecipe = new Recipe(duplicateData);
    const savedDuplicate = await duplicatedRecipe.save();

    // Add the duplicated recipe to the user's savedRecipes array using $addToSet for atomic operation
    await User.updateOne(
      { _id: user._id },
      { $addToSet: { savedRecipes: savedDuplicate._id } }
    );
    console.log('[duplicateRecipe] Added duplicated recipe to user savedRecipes array');

    console.log('[duplicateRecipe] Recipe duplicated successfully:', savedDuplicate._id);
    res.status(201).json({
      success: true,
      message: "Recipe duplicated successfully.",
      data: savedDuplicate,
    });
  } catch (error) {
    console.error('[duplicateRecipe] Error duplicating recipe:', error);
    res.status(500).json({ 
      success: false, 
      message: "Error duplicating recipe.", 
      error: error.message,
      stack: process.env.NODE_ENV === 'development' ? error.stack : undefined
    });
  }
};
