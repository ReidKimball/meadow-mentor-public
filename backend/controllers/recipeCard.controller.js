/**
 * @desc    Rotate a recipe image
 * @route   PATCH /api/recipes/:id/images/rotate
 * @access  Private
 */
export const rotateRecipeImage = async (req, res) => {
  const { id: recipeId } = req.params;
  const { imageName } = req.body; // e.g., users/uid/recipes/rid/image-original.webp
  const { user } = req;

  try {
    const recipe = await Recipe.findById(recipeId).populate('generatedBy');

    if (!recipe) {
      return res.status(404).json({ success: false, message: 'Recipe not found.' });
    }
    // Compare the firebaseUID from the populated user with the uid from the token
    if (recipe.generatedBy.firebaseUID !== user.uid) {
      return res.status(403).json({ success: false, message: 'User not authorized.' });
    }

    let gcsPath;
    if (imageName.startsWith('http')) {
      // It's a full URL, parse it to get the GCS path.
      gcsPath = new URL(imageName).pathname.substring(1).split('/').slice(1).join('/');
    } else {
      // It's already a path.
      gcsPath = imageName;
    }

    // Derive other image names from the GCS path
    const version = gcsPath.match(/-v(\d+)/);
    const basePath = gcsPath.replace(/-v\d+-(thumbnail|display|original)\.webp$/, '');

    const originalGcsPath = `${basePath}-v${version[1]}-original.webp`;
    const displayGcsPath = `${basePath}-v${version[1]}-display.webp`;
    const thumbGcsPath = `${basePath}-v${version[1]}-thumbnail.webp`;

    // Download all three images as buffers
    const [originalBuffer, displayBuffer, thumbBuffer] = await Promise.all([
      downloadFileAsBuffer(originalGcsPath),
      downloadFileAsBuffer(displayGcsPath),
      downloadFileAsBuffer(thumbGcsPath),
    ]);

    // Rotate buffers
    const [rotatedOriginal, rotatedDisplay, rotatedThumb] = await Promise.all([
      sharp(originalBuffer).rotate(90).toBuffer(),
      sharp(displayBuffer).rotate(90).toBuffer(),
      sharp(thumbBuffer).rotate(90).toBuffer(),
    ]);

    // Upload rotated buffers, overwriting the originals
    await Promise.all([
      uploadBufferToGCS(rotatedOriginal, originalGcsPath),
      uploadBufferToGCS(rotatedDisplay, displayGcsPath),
      uploadBufferToGCS(rotatedThumb, thumbGcsPath),
    ]);

    // The URLs don't change, so we just send a success message.
    res.status(200).json({ success: true, message: 'Image rotated successfully.' });

  } catch (error) {
    console.error('--- ERROR in rotateRecipeImage ---', error);
    res.status(500).json({ success: false, message: error.message || 'Server error rotating image.' });
  }
};

