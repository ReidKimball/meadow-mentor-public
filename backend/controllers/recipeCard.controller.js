// @desc    Toggle the public status of a recipe
// @route   PATCH /api/recipes/:id/toggle-public
// @access  Private
export const togglePublicStatus = async (req, res) => {
  try {
    const { id: recipeId } = req.params;
    const user = await User.findOne({ firebaseUID: req.user.uid });

    const { visibility } = req.body || {};

    if (!user) {
      return res.status(404).json({ success: false, message: "User not found." });
    }

    const recipe = await Recipe.findById(recipeId);

    if (!recipe) {
      return res.status(404).json({ success: false, message: "Recipe not found." });
    }

    // Check if the user is the one who generated the recipe
    if (!recipe.generatedBy || !recipe.generatedBy.equals(user._id)) {
      return res.status(403).json({ success: false, message: "User not authorized to change this recipe's status." });
    }

    if (visibility !== undefined) {
      if (!['private', 'unlisted', 'public'].includes(visibility)) {
        return res.status(400).json({
          success: false,
          message: "Invalid visibility value. Must be 'private', 'unlisted', or 'public'.",
        });
      }

      recipe.visibility = visibility;
    } else {
      const nextVisibility = recipe.visibility === 'public' ? 'private' : 'public';
      recipe.visibility = nextVisibility;
    }

    await recipe.save();

    res.status(200).json({ 
      success: true, 
      message: `Recipe visibility updated to ${recipe.visibility}.`,
      data: { visibility: recipe.visibility, isPublic: recipe.isPublic, slug: recipe.slug }
    });
  } catch (error) {
    console.error('--- ERROR in togglePublicStatus ---', error);
    res.status(500).json({ 
      success: false, 
      message: "Error toggling recipe public status.", 
      error: error.message,
      stack: process.env.NODE_ENV === 'development' ? error.stack : undefined
    });
  }
};

// @desc    Get a recipe by slug (public, saved by user, or the special first healing meal)
// @route   GET /api/recipes/slug/:slug
// @access  Private (checks ownership for non-public recipes)
export const getRecipeBySlug = async (req, res) => {
  try {
    const { slug } = req.params;
    const recipe = await Recipe.findOne({ slug });

    if (!recipe) {
      return res.status(404).json({ success: false, message: 'Recipe not found.' });
    }

    const isExternallyVisible = recipe.visibility && recipe.visibility !== 'private';

    // If the recipe is externally visible (public/unlisted) or it's the special first healing meal,
    // any authenticated user can view it.
    if (isExternallyVisible || recipe.isPublic || recipe.isFirstHealingMeal) {
      return res.status(200).json({ success: true, data: recipe });
    }

    // For private recipes, check if the user generated it or has saved it.
    const user = await User.findOne({ firebaseUID: req.user.uid });

    // If no user is found, they can't access a private recipe.
    if (!user) {
        return res.status(403).json({ success: false, message: 'User not found. Access denied.' });
    }

    // Check if the user is the generator of the recipe.
    const isGenerator = recipe.generatedBy && recipe.generatedBy.equals(user._id);

    // Check if the recipe ID is in the user's savedRecipes array.
    const isSaved = user.savedRecipes.some(savedId => savedId.equals(recipe._id));

    if (isGenerator || isSaved) {
      return res.status(200).json({ success: true, data: recipe });
    }

    // If none of the above, the user is not authorized.
    return res.status(403).json({ success: false, message: 'User not authorized to view this recipe.' });

  } catch (error) {
    console.error('Error fetching recipe by slug:', error);
    res.status(500).json({ success: false, message: 'Server error fetching recipe', error: error.message });
  }
};

// @desc    Upload an image for a recipe card
// @route   POST /api/recipes/:id/image
// @access  Private
export const uploadRecipeImage = async (req, res) => {
  try {
    const { id: recipeId } = req.params;
    const user = await User.findOne({ firebaseUID: req.user.uid });

    if (!user) {
      return res.status(404).json({ success: false, message: "User not found." });
    }

    if (!req.file) {
      return res.status(400).json({ success: false, message: "No image file uploaded." });
    }

    const recipe = await Recipe.findById(recipeId);

    if (!recipe) {
      return res.status(404).json({ success: false, message: "Recipe not found." });
    }

    // Authorization check: Only the user who generated the recipe can upload an image.
    if (!recipe.generatedBy || !recipe.generatedBy.equals(user._id)) {
      return res.status(403).json({ success: false, message: "User not authorized to upload an image for this recipe." });
    }

    // Increment the image version
    recipe.imageVersion = (recipe.imageVersion || 0) + 1;
    const newVersion = recipe.imageVersion;

    // Define image sizes and the new versioned filename
    const sizes = {
      thumbnail: { width: 480, fit: 'cover', quality: 80 },
      display: { width: 800, fit: 'inside', quality: 85 },
      original: { quality: 90 },
    };
    const filenameBase = `${recipe.slug}-v${newVersion}`;

    const imageUrls = {};
    const imageProcessor = sharp(req.file.buffer);

    for (const [key, settings] of Object.entries(sizes)) {
      let processor = imageProcessor.clone();
      if (settings.width) {
        processor = processor.resize({ width: settings.width, height: settings.height, fit: settings.fit });
      }
      const buffer = await processor.webp({ quality: settings.quality }).toBuffer();
      const destination = `users/${user._id}/recipes/${recipeId}/${filenameBase}-${key}.webp`;
      imageUrls[key] = await uploadBufferToGCS(buffer, destination);
    }

    // Update recipe with new image URLs and save
    recipe.recipeImage = imageUrls;
    await recipe.save();

    res.status(200).json({ 
      message: 'Image uploaded successfully.',
      imageUrls: recipe.recipeImage
    });
  } catch (error) {
    console.error('Error uploading recipe image:', error);
    res.status(500).json({ 
      success: false, 
      message: "Error uploading image.", 
      error: error.message, 
      stack: process.env.NODE_ENV === 'development' ? error.stack : undefined
    });
  }
};

