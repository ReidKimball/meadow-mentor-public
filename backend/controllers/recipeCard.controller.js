/**
 * @constant ENABLE_RECIPE_IMAGE_CROP_4_3
 * @description Toggles center-cropping generated images to 4:3 before resizing.
 * Set to "true" to enforce 4:3, or "false"/unset to keep original output.
 * @type {boolean}
 */
const ENABLE_RECIPE_IMAGE_CROP_4_3 = String(process.env.ENABLE_RECIPE_IMAGE_CROP_4_3).toLowerCase() === 'true';

/**
 * @function cropImageBufferToFourThree
 * @description Crops a buffer to a centered 4:3 aspect ratio using Sharp,
 * preserving the source resolution when possible.
 * @param {Buffer} buffer - Source image buffer.
 * @returns {Promise<Buffer>} Cropped image buffer.
 */
const cropImageBufferToFourThree = async (buffer) => {
  const image = sharp(buffer);
  const metadata = await image.metadata();

  if (!metadata?.width || !metadata?.height) {
    console.warn('[generateRecipeImageController] Missing image metadata; skipping 4:3 crop.');
    return buffer;
  }

  const targetRatio = 4 / 3;
  let cropWidth = metadata.width;
  let cropHeight = Math.round(metadata.width / targetRatio);

  if (cropHeight > metadata.height) {
    cropHeight = metadata.height;
    cropWidth = Math.round(metadata.height * targetRatio);
  }

  const left = Math.max(0, Math.round((metadata.width - cropWidth) / 2));
  const top = Math.max(0, Math.round((metadata.height - cropHeight) / 2));

  return image
    .extract({ left, top, width: cropWidth, height: cropHeight })
    .toBuffer();
};

