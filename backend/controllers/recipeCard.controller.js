export const updateRecipeIngredients = async (req, res) => {
  try {
    const { id: recipeId } = req.params;
    const { ingredients } = req.body;
    const user = await User.findOne({ firebaseUID: req.user.uid });

    if (!user) {
      return res.status(404).json({ success: false, message: "User not found." });
    }

    if (!ingredients || !Array.isArray(ingredients)) {
      return res.status(400).json({ success: false, message: "Valid ingredients array is required." });
    }

    const recipe = await Recipe.findById(recipeId);

    if (!recipe) {
      return res.status(404).json({ success: false, message: "Recipe not found." });
    }

    // Check if the user is the one who generated the recipe
    if (!recipe.generatedBy || !recipe.generatedBy.equals(user._id)) {
      return res.status(403).json({ success: false, message: "User not authorized to update this recipe." });
    }

    // Update the ingredients
    recipe.ingredients = ingredients;
    await recipe.save();

    res.status(200).json({ 
      success: true, 
      message: "Recipe ingredients updated successfully.",
      data: recipe
    });
  } catch (error) {
    console.error('--- ERROR in updateRecipeIngredients ---', error);
    res.status(500).json({ 
      success: false, 
      message: "Error updating recipe ingredients.", 
      error: error.message,
      stack: process.env.NODE_ENV === 'development' ? error.stack : undefined
    });
  }
};

