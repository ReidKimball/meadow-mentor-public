/**
 * @desc    Delete a specific recipe image and its versions
 * @route   DELETE /api/recipes/:id/images
 * @access  Private
 */
export const deleteRecipeImage = async (req, res) => {
  const { id: recipeId } = req.params;
  const { imageName } = req.body; // Expects the full GCS object name, e.g., 'prefix/users/.../slug-v1-thumbnail.webp'
  const firebaseUid = req.user.uid;

  if (!imageName) {
    return res.status(400).json({ message: 'Image name is required.' });
  }

  try {
    const [recipe, user] = await Promise.all([
      Recipe.findById(recipeId),
      User.findOne({ firebaseUID: firebaseUid })
    ]);

    if (!recipe) {
      return res.status(404).json({ message: 'Recipe not found.' });
    }

    if (!user) {
      return res.status(404).json({ message: 'User not found.' });
    }

    if (!recipe.generatedBy || !recipe.generatedBy.equals(user._id)) {
      return res.status(403).json({ message: 'Forbidden: You can only delete images for your own recipes.' });
    }

    // From '...-thumbnail.webp', get the base path to delete all sizes
    const basePath = imageName.replace(/-(thumbnail|display|original)\.webp$/, '');

    // Delete all three image sizes from GCS
    await Promise.all([
      deleteFileFromGCS(`${basePath}-thumbnail.webp`),
      deleteFileFromGCS(`${basePath}-display.webp`),
      deleteFileFromGCS(`${basePath}-original.webp`),
    ]);

    // If the deleted image was the current cover, clear the fields
    const gcsPublicBase = process.env.GCS_PUBLIC_BASE;
    const bucketName = process.env.GCS_BUCKET_NAME;
    const currentThumbnailUrl = `${gcsPublicBase}/${bucketName}/${imageName}`;

    if (recipe.recipeImage?.thumbnail === currentThumbnailUrl) {
      recipe.recipeImage = { thumbnail: '', display: '', original: '' };
      await recipe.save();
    }

    res.status(200).json({ success: true, message: 'Image deleted successfully.' });

  } catch (error) {
    console.error('Error deleting recipe image:', error);
    res.status(500).json({ success: false, message: 'Server error while deleting image.' });
  }
};

