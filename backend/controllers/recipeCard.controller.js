// @desc    Save a recipe to a user's collection
// @route   POST /api/recipes/:id/save
// @access  Private
export const saveRecipe = async (req, res) => {

  try {
    const { id: recipeId } = req.params;
    const { rating } = req.body; // Destructure rating from the request body
    const firebaseUID = req.user.uid;


    const [user, recipe] = await Promise.all([
      User.findOne({ firebaseUID }),
      Recipe.findById(recipeId),
    ]);



    if (!user) {
      return res.status(404).json({ success: false, message: "User not found." });
    }
    if (!recipe) {
      return res.status(404).json({ success: false, message: "Recipe not found." });
    }

    // Handle the rating update
    if (rating && rating > 0) {
      const existingRatingIndex = recipe.ratings.findIndex(
        (r) => r.user.equals(user._id)
      );

      if (existingRatingIndex > -1) {
        // User has already rated, update the rating

        recipe.ratings[existingRatingIndex].rating = rating;
      } else {
        // User is rating for the first time

        recipe.ratings.push({ user: user._id, rating });
      }
    }

    // Add recipe to user's saved list and user to recipe's savedBy list
    // Use $addToSet to prevent duplicates
    user.savedRecipes.addToSet(recipeId);
    recipe.savedBy.addToSet(user._id);

    await Promise.all([user.save(), recipe.save()]);


    res.status(200).json({ 
      success: true, 
      message: "Recipe saved and rating updated successfully.",
      data: {
        averageRating: recipe.averageRating
      }
    });
  } catch (error) {
    console.error('--- ERROR IN saveRecipe ---', error);
    res.status(500).json({ success: false, message: "Error saving recipe.", error: error.message });
  }
};

